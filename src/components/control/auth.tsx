"use client";
import Link from "next/link";
import Image from "next/image";
import { useState } from "react";
import type { AuthState } from "@/lib/control/model";
import { api } from "./api";

export function AuthGate({
  state,
  onState,
}: {
  state: AuthState;
  onState: (value: AuthState) => void;
}) {
  const [busy, setBusy] = useState(false),
    [error, setError] = useState(""),
    [enrollment, setEnrollment] = useState<{
      factorId: string;
      qrCode: string;
      secret: string;
    } | null>(null);
  async function submit(event: React.FormEvent<HTMLFormElement>) {
    event.preventDefault();
    setError("");
    setBusy(true);
    const data = new FormData(event.currentTarget);
    try {
      const next =
        state.step === "login"
          ? await api<AuthState>("auth/login", {
              email: data.get("email"),
              password: data.get("password"),
            })
          : await api<AuthState>("auth/verify", {
              factorId: enrollment?.factorId || state.factorId,
              code: data.get("code"),
            });
      setEnrollment(null);
      onState(next);
    } catch (e) {
      setError((e as Error).message);
    } finally {
      setBusy(false);
    }
  }
  async function enroll() {
    setBusy(true);
    setError("");
    try {
      setEnrollment(await api("auth/enroll", {}));
    } catch (e) {
      setError((e as Error).message);
    } finally {
      setBusy(false);
    }
  }
  return (
    <main id="control-main" className="auth-page">
      <section className="auth-card">
        <Link className="control-wordmark" href="/uz">
          sardorcodev<span> / control</span>
        </Link>
        <div className="eyebrow">SHAXSIY USTAXONA</div>
        <h1>
          {state.step === "login"
            ? "Boshqaruvga kirish"
            : state.step === "enroll"
              ? "Ikki bosqichli himoya"
              : state.step === "verify"
                ? "Kirishni tasdiqlash"
                : "Ulanish tayyor emas"}
        </h1>
        {state.step === "unavailable" ? (
          <>
            <p>Baza yoki kirish xizmati javob bermayapti. Bir ozdan keyin qayta urinib ko‘ring.</p>
            <button onClick={() => window.location.reload()}>Qayta tekshirish</button>
          </>
        ) : (
          <>
            <p>
              {state.step === "login"
                ? "Portfolio kontenti va sozlamalarini bitta joydan boshqaring."
                : "Google Authenticator, 1Password yoki boshqa TOTP ilovasidagi 6 xonali kod kerak."}
            </p>
            {state.step === "enroll" && !enrollment ? (
              <>
                <p>
                  Authenticator o‘rnating va uning zaxira nusxasini xavfsiz saqlang. Qurilma
                  yo‘qolsa, hisobni Supabase orqali tiklash mumkin.
                </p>
                <button disabled={busy} onClick={enroll}>
                  Authenticator ulash
                </button>
              </>
            ) : (
              <form onSubmit={submit}>
                {state.step === "login" ? (
                  <>
                    <label>
                      Email
                      <input
                        name="email"
                        type="email"
                        autoComplete="username"
                        required
                        defaultValue="sardorcodev@gmail.com"
                      />
                    </label>
                    <label>
                      Parol
                      <input
                        name="password"
                        type="password"
                        autoComplete="current-password"
                        required
                        maxLength={256}
                      />
                    </label>
                  </>
                ) : (
                  <>
                    {enrollment && (
                      <div className="enrollment">
                        {/* This QR is generated by Supabase, never from public content. */}
                        <Image
                          unoptimized
                          src={enrollment.qrCode}
                          alt="Authenticator ilovasida skaner qilinadigan QR kod"
                          width={224}
                          height={224}
                        />
                        <details>
                          <summary>QR ishlamasa: qo‘lda kiritish</summary>
                          <code>{enrollment.secret}</code>
                        </details>
                      </div>
                    )}
                    <label>
                      Authenticator kodi
                      <input
                        name="code"
                        inputMode="numeric"
                        autoComplete="one-time-code"
                        pattern="[0-9]{6}"
                        maxLength={6}
                        minLength={6}
                        required
                        autoFocus
                      />
                    </label>
                  </>
                )}
                <button disabled={busy}>
                  {busy ? "Tekshirilmoqda…" : state.step === "login" ? "Kirish" : "Tasdiqlash"}
                </button>
              </form>
            )}
          </>
        )}
        {error && (
          <p role="alert" className="notice error">
            {error}
          </p>
        )}
        <Link className="muted-link" href="/uz">
          ← Portfolio saytiga
        </Link>
      </section>
    </main>
  );
}
